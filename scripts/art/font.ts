const ALIAS: Record<string, string> = { '‘': "'", '’': "'", '“': '"', '”': '"', '–': '-' };

export const FONT_LINE = 12;

export function buildFont(file = 'font.png') {
  const chars = Object.keys(G);
  const cellH = 10;
  const glyphs = chars.map((ch) => {
    const rows = G[ch].split(' ');
    const w = rows[0].length;
    return { ch, rows, w };
  });
  const totalW = glyphs.reduce((s, g) => s + g.w + 1, 0);
  const cols = 256;
  // layout in rows of 256px
  let x = 0, y = 0;
  const placed = glyphs.map((g) => {
    if (x + g.w + 1 > cols) { x = 0; y += cellH; }
    const p = { ...g, x, y };
    x += g.w + 1;
    return p;
  });
  void totalW;
  const H = y + cellH;
  let h2 = 1; while (h2 < H) h2 <<= 1;
  const img = new Img(cols, h2);
  for (const p of placed)
    p.rows.forEach((r, j) => [...r].forEach((c, i) => c === '#' && img.put(p.x + i, p.y + j, hex('#ffffff'))));
  const charXml = (id: number, p: (typeof placed)[number]) =>
    `<char id="${id}" x="${p.x}" y="${p.y}" width="${p.w}" height="${cellH}" xoffset="0" yoffset="0" xadvance="${p.ch === ' ' ? 3 : p.w + 1}" page="0" chnl="15"/>`;
  const entries = placed.map((p) => charXml(p.ch.codePointAt(0)!, p));
  for (const [a, b] of Object.entries(ALIAS)) {
    const p = placed.find((q) => q.ch === b)!;
    entries.push(charXml(a.codePointAt(0)!, p));
  }
  const xml = `<?xml version="1.0"?>
<font>
  <info face="cardamom" size="${cellH}" bold="0" italic="0" charset="" unicode="1" stretchH="100" smooth="0" aa="0" padding="0,0,0,0" spacing="0,0"/>
  <common lineHeight="${FONT_LINE}" base="7" scaleW="${cols}" scaleH="${h2}" pages="1" packed="0"/>
  <pages><page id="0" file="${file}"/></pages>
  <chars count="${entries.length}">
    ${entries.join('\n    ')}
  </chars>
</font>`;
  return { img, xml };
}
